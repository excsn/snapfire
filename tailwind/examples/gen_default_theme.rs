//! Writes `src/compat/default_theme.rs` from Tailwind's `src/compat/default-theme.ts`: the v3
//! default theme that `theme(fontWeight.semibold)` and other dotted paths fall back to.
//!
//! ```sh
//! cargo run -p snapfire_tailwind --example gen_default_theme -- <tailwindcss>/packages/tailwindcss/src/compat/default-theme.ts tailwind/src/compat/default_theme.rs
//! ```

use oxc_allocator::Allocator;
use oxc_ast::ast::{ArrayExpressionElement, Expression, ObjectPropertyKind, PropertyKey, Statement};
use oxc_parser::Parser;
use oxc_span::SourceType;

fn quote(s: &str) -> String {
  format!("{s:?}")
}

fn key(k: &PropertyKey) -> String {
  match k {
    PropertyKey::StaticIdentifier(id) => id.name.to_string(),
    PropertyKey::StringLiteral(s) => s.value.display().to_string(),
    PropertyKey::NumericLiteral(n) => n.raw.map(|r| r.to_string()).unwrap_or_else(|| n.value.to_string()),
    other => panic!("unsupported key {other:?}"),
  }
}

fn expr(e: &Expression) -> String {
  match e {
    Expression::StringLiteral(s) => format!("E::Str({})", quote(&s.value.display().to_string())),
    Expression::NumericLiteral(n) => format!(
      "E::Str({})",
      quote(&n.raw.map(|r| r.to_string()).unwrap_or_else(|| n.value.to_string()))
    ),
    Expression::ArrayExpression(a) => {
      let items: Vec<String> = a
        .elements
        .iter()
        .map(|el| match el {
          ArrayExpressionElement::SpreadElement(_) => panic!("spread in array"),
          other => expr(other.as_expression().expect("an array item")),
        })
        .collect();
      format!("E::Arr(vec![{}])", items.join(", "))
    }
    Expression::ObjectExpression(o) => {
      let mut entries = Vec::new();
      for p in &o.properties {
        match p {
          ObjectPropertyKind::ObjectProperty(p) => {
            entries.push(format!("Entry::Prop({}, {})", quote(&key(&p.key)), expr(&p.value)))
          }
          ObjectPropertyKind::SpreadProperty(s) => match &s.argument {
            Expression::Identifier(id) if id.name.starts_with("bare") => {
              entries.push("Entry::Prop(\"__BARE_VALUE__\", E::Bare)".to_owned())
            }
            Expression::Identifier(id) if id.name == "colors" => entries.push("Entry::Spread(E::Colors)".to_owned()),
            other => entries.push(format!("Entry::Spread({})", expr(other))),
          },
        }
      }
      format!("E::Obj(vec![{}])", entries.join(", "))
    }
    Expression::ParenthesizedExpression(p) => expr(&p.expression),
    Expression::ArrowFunctionExpression(f) => {
      let body = f
        .body
        .as_expression()
        .expect("an arrow function with an expression body");
      format!("E::Fn(Box::new({}))", expr(body))
    }
    Expression::CallExpression(c) => {
      let Expression::Identifier(callee) = &c.callee else {
        panic!("a call to theme()")
      };
      assert_eq!(callee.name, "theme");
      let path = match c.arguments.first().and_then(|a| a.as_expression()) {
        Some(Expression::StringLiteral(s)) => s.value.display().to_string(),
        _ => panic!("theme() takes a string path"),
      };
      let fallback = c.arguments.get(1).and_then(|a| a.as_expression()).map(expr);
      match fallback {
        Some(f) => format!("E::Theme({}, Some(Box::new({f})))", quote(&path)),
        None => format!("E::Theme({}, None)", quote(&path)),
      }
    }
    other => panic!("unsupported expression {other:?}"),
  }
}

fn main() {
  let args: Vec<String> = std::env::args().collect();
  let source = std::fs::read_to_string(&args[1]).expect("default-theme.ts");
  let allocator = Allocator::default();
  let parsed = Parser::new(&allocator, &source, SourceType::ts()).parse();
  assert!(parsed.diagnostics.is_empty());

  let theme = parsed
    .program
    .body
    .iter()
    .find_map(|s| match s {
      Statement::ExportDefaultDeclaration(d) => match &d.declaration {
        oxc_ast::ast::ExportDefaultDeclarationKind::ObjectExpression(o) => Some(o),
        oxc_ast::ast::ExportDefaultDeclarationKind::TSSatisfiesExpression(s) => match &s.expression {
          Expression::ObjectExpression(o) => Some(o),
          _ => None,
        },
        _ => None,
      },
      _ => None,
    })
    .expect("export default { … }");

  let mut out = String::new();
  out.push_str("//! Tailwind v4.3.2's `src/compat/default-theme.ts`, generated by `examples/gen_default_theme.rs`.\n");
  out.push_str("//! Copyright (c) Tailwind Labs, Inc. Released under the MIT License, see `css/LICENSE-TAILWIND`.\n\n");
  out.push_str("use super::theme::{E, Entry};\n\n");
  out.push_str("pub(super) fn default_theme() -> Vec<(&'static str, E)> {\n  vec![\n");
  for p in &theme.properties {
    let ObjectPropertyKind::ObjectProperty(p) = p else {
      panic!("a spread at the top level")
    };
    out.push_str(&format!("    ({}, {}),\n", quote(&key(&p.key)), expr(&p.value)));
  }
  out.push_str("  ]\n}\n");
  std::fs::write(&args[2], out).expect("the output file");
}
