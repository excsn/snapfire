//! `.mdx` and `.md` files in the build: the module the lowerer reads for each,
//! the component map `mdx-components.tsx` returns, the collections listed in
//! `generated/content.ts` and the copy the browser compiles when a file
//! renders there.

use std::collections::BTreeMap;
use std::path::Path;

use snapfire_fsr_host::config::MdxSection;

use crate::BuildError;

/// The file at the app's root whose `useMDXComponents` maps markdown's elements.
pub const COMPONENTS: &str = "mdx-components.tsx";

/// The collections module, relative to the app.
pub const CONTENT_MODULE: &str = snapfire_fsr_lower::CONTENT_MODULE;

/// The type declarations an import of an `.mdx` or `.md` file is checked against.
pub const DECLARATIONS_FILE: &str = "generated/mdx.d.ts";

pub const DECLARATIONS: &str = "// Generated by fsr build. Do not edit.\n\ndeclare module \"*.mdx\" {\n  export const meta: any;\n  export const toc: { depth: number; id: string; text: string }[];\n  const MDXContent: (props: { components?: Record<string, unknown>; [prop: string]: unknown }) => any;\n  export default MDXContent;\n}\n\ndeclare module \"*.md\" {\n  export const meta: any;\n  export const toc: { depth: number; id: string; text: string }[];\n  const MDXContent: (props: { components?: Record<string, unknown>; [prop: string]: unknown }) => any;\n  export default MDXContent;\n}\n\ndeclare module \"mdx/types\" {\n  export type MDXComponents = Record<string, unknown>;\n}\n";

/// How the build reads MDX, from `[mdx]` and the features this fsr carries.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct Settings {
  pub gfm: bool,
  pub heading_ids: bool,
  pub frontmatter: bool,
  pub highlight: bool,
  pub collections: BTreeMap<String, String>,
}

/// Whether this fsr reads `.mdx` and `.md` files.
pub const BUILT: bool = cfg!(feature = "mdx");

fn needs(what: impl Into<String>, feature: &'static str) -> BuildError {
  BuildError::MdxFeature { what: what.into(), feature }
}

/// `[mdx]` as this fsr can honour it: a key whose feature it was built
/// without is refused naming that feature.
pub fn settings(section: &MdxSection) -> Result<Settings, BuildError> {
  if !BUILT && !section.collections.is_empty() {
    return Err(needs("`[mdx.collections]`", "mdx"));
  }
  if section.frontmatter && !cfg!(feature = "mdx-frontmatter") {
    return Err(needs("`[mdx] frontmatter = true`", "mdx-frontmatter"));
  }
  if section.highlight == Some(true) && !cfg!(feature = "mdx-highlight") {
    return Err(needs("`[mdx] highlight = true`", "mdx-highlight"));
  }
  Ok(Settings { gfm: section.gfm, heading_ids: section.heading_ids, frontmatter: section.frontmatter, highlight: section.highlight.unwrap_or(cfg!(feature = "mdx-highlight")), collections: section.collections.clone() })
}

/// The refusal for an `.mdx` or `.md` route or import in an fsr built without `mdx`.
pub fn unbuilt(file: &Path) -> BuildError {
  needs(format!("{}", file.display()), "mdx")
}

/// What the build learned converting files: the classes the highlighter
/// wrote and what each conversion left out, by file and position.
#[derive(Debug, Default, Clone)]
#[non_exhaustive]
pub struct Log {
  pub classes: std::collections::BTreeSet<String>,
  pub warnings: Vec<(String, usize, usize, String)>,
  /// Every file converted, for the browser's copy.
  pub files: Vec<String>,
}

#[cfg(feature = "mdx")]
pub use built::*;

#[cfg(feature = "mdx")]
mod built {
  use std::cell::RefCell;
  use std::path::Path;
  use std::rc::Rc;

  use snapfire_fsr_lower::component::{ComponentSet, Override, Transformed};
  use snapfire_fsr_lower::{MappedValue, Origin, OriginSegment};
  use snapfire_fsr_mdx::{ClassAttr, Format, Mapped, Options, Target};

  use super::{Log, Settings, COMPONENTS, CONTENT_MODULE};
  use crate::BuildError;

  /// The specifier every module the transform writes imports the map from.
  const COMPONENTS_SPECIFIER: &str = "@app/mdx-components";

  /// What [`install`] hands the rest of the build.
  #[non_exhaustive]
  pub struct Installed {
    pub log: Rc<RefCell<Log>>,
    /// The keys `mdx-components.tsx` maps, `None` when the app has no such file.
    pub mapped: Option<Vec<String>>,
    pub class_attr: ClassAttr,
    pub settings: Settings,
  }

  fn options(file: &str, settings: &Settings, class_attr: ClassAttr, target: Target) -> Result<Options, String> {
    let format = Format::of(file).ok_or_else(|| format!("{file} is neither `.mdx` nor `.md`"))?;
    let mut options = Options::new(format, target);
    options.gfm = settings.gfm;
    options.heading_ids = settings.heading_ids;
    options.frontmatter = settings.frontmatter;
    options.highlight = settings.highlight;
    options.class_attr = class_attr;
    Ok(options)
  }

  /// `mdx-components.tsx` with each mapped element exported under a name the
  /// written modules import, the keys it maps and that source.
  fn component_map(app: &Path) -> Result<Option<(Vec<String>, String)>, BuildError> {
    let path = app.join(COMPONENTS);
    if !path.is_file() {
      return Ok(None);
    }
    let source = std::fs::read_to_string(&path).map_err(|e| BuildError::Io(path.clone(), e))?;
    let entries = snapfire_fsr_lower::mdx_component_map(COMPONENTS, &source)?;
    let mut extended = source.clone();
    extended.push('\n');
    let mut keys = Vec::new();
    for (key, value) in entries {
      match value {
        MappedValue::Name(name) => extended.push_str(&format!("export {{ {name} as __mdx_{key} }};\n")),
        MappedValue::Expr(range) => extended.push_str(&format!("export const __mdx_{key} = {};\n", &source[range])),
      }
      keys.push(key);
    }
    Ok(Some((keys, extended)))
  }

  /// `set` reading `.mdx` and `.md` through the converter, with the
  /// application's map placed for every element it names.
  pub fn install(app: &Path, set: ComponentSet, settings: &Settings, class_attr: ClassAttr) -> Result<(ComponentSet, Installed), BuildError> {
    let log = Rc::new(RefCell::new(Log::default()));
    let map = component_map(app)?;
    let mapped: Vec<Mapped> = map.iter().flat_map(|(keys, _)| keys.iter()).map(|key| Mapped::new(key.clone(), COMPONENTS_SPECIFIER.to_owned(), format!("__mdx_{key}"))).collect();
    let held = settings.clone();
    let written = log.clone();
    let transform = Rc::new(move |file: &str, source: &str, overrides: &[Override]| -> Result<Transformed, String> {
      let mut options = options(file, &held, class_attr, Target::Lowered)?;
      options.mapped = mapped.clone();
      for o in overrides {
        options.mapped.retain(|m| m.key != o.key);
        options.mapped.push(Mapped::new(o.key.clone(), o.specifier.clone(), o.export.clone()));
      }
      let converted = snapfire_fsr_mdx::convert(source, &options).map_err(|e| e.to_string())?;
      let mut log = written.borrow_mut();
      log.classes.extend(converted.classes.iter().cloned());
      if !log.files.iter().any(|f| f == file) {
        log.files.push(file.to_owned());
        for w in &converted.warnings {
          log.warnings.push((file.to_owned(), w.line, w.column, w.message.clone()));
        }
      }
      let segments = converted.segments.iter().map(|s| OriginSegment::new(s.generated, s.len, s.original, s.verbatim)).collect();
      Ok(Transformed::new(converted.tsx, Some(Origin::new(source.to_owned(), segments))))
    });
    let mut set = set.with_transform(transform);
    if let Some((_, extended)) = &map {
      set = set.provide(COMPONENTS, extended.clone());
    }
    Ok((set, Installed { log, mapped: map.map(|(keys, _)| keys), class_attr, settings: settings.clone() }))
  }

  /// `generated/content.ts`: per collection, every `.mdx` and `.md` file in
  /// its directory by name, with its slug, its name there, its `meta`, its `toc` and its first paragraph as `excerpt`.
  pub fn collections(app: &Path, installed: &Installed) -> Result<Option<String>, BuildError> {
    if installed.settings.collections.is_empty() {
      return Ok(None);
    }
    let mut imports = String::new();
    let mut body = String::new();
    let mut n = 0;
    for (name, dir) in &installed.settings.collections {
      let full = app.join(dir);
      let mut files: Vec<String> = std::fs::read_dir(&full)
        .map_err(|e| BuildError::Io(full.clone(), e))?
        .filter_map(|e| e.ok())
        .filter(|e| e.path().is_file())
        .filter_map(|e| e.file_name().to_str().map(str::to_owned))
        .filter(|f| Format::of(f).is_some())
        .collect();
      files.sort();
      body.push_str(&format!("\nexport const {name} = [\n"));
      for file in files {
        let rel = format!("{dir}/{file}");
        let source = std::fs::read_to_string(app.join(&rel)).map_err(|e| BuildError::Io(app.join(&rel), e))?;
        let options = options(&rel, &installed.settings, installed.class_attr, Target::Lowered).map_err(|message| BuildError::Mdx { file: rel.clone(), message })?;
        let converted = snapfire_fsr_mdx::convert(&source, &options).map_err(|e| BuildError::Mdx { file: rel.clone(), message: e.to_string() })?;
        let slug = file.rsplit_once('.').map(|(stem, _)| stem).unwrap_or(&file);
        let specifier = format!("../{rel}");
        let mut named = Vec::new();
        let meta = match converted.meta {
          true => {
            named.push(format!("meta as meta{n}"));
            format!("meta{n}")
          }
          false => "{}".to_owned(),
        };
        let toc = match converted.exports.iter().any(|e| e == "toc") {
          true => {
            named.push(format!("toc as toc{n}"));
            format!("toc{n}")
          }
          false => "[]".to_owned(),
        };
        if !named.is_empty() {
          imports.push_str(&format!("import {{ {} }} from {};\n", named.join(", "), serde_json::to_string(&specifier).expect("a string")));
        }
        let excerpt = serde_json::to_string(&converted.excerpt).expect("an excerpt serializes");
        body.push_str(&format!("  {{ slug: {}, file: {}, meta: {meta}, toc: {toc}, excerpt: {excerpt} }},\n", serde_json::to_string(slug).expect("a string"), serde_json::to_string(&file).expect("a string")));
        n += 1;
      }
      body.push_str("];\n");
    }
    let _ = CONTENT_MODULE;
    Ok(Some(format!("// Generated by fsr build from [mdx.collections]. Do not edit.\n\n{imports}{body}")))
  }

  /// The module the browser compiles for `file` in place of its source, with
  /// the map read at render time.
  pub fn browser_copy(app: &Path, file: &str, installed: &Installed) -> Result<String, BuildError> {
    let source = std::fs::read_to_string(app.join(file)).map_err(|e| BuildError::Io(app.join(file), e))?;
    let mut options = options(file, &installed.settings, installed.class_attr, Target::Browser).map_err(|message| BuildError::Mdx { file: file.to_owned(), message })?;
    options.provider = installed.mapped.as_ref().map(|_| COMPONENTS_SPECIFIER.to_owned());
    snapfire_fsr_mdx::convert(&source, &options).map(|c| c.tsx).map_err(|e| BuildError::Mdx { file: file.to_owned(), message: e.to_string() })
  }
}
