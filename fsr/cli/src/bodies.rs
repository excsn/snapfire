//! `generated/bodies.rs`: the plan's lowered bodies as Rust, for a production build to compile into the application. The application includes the file and registers `BODIES` with `HostBuilder::bodies`; the host attaches each to the body whose plan it was written from, and a body whose plan no longer matches runs interpreted.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use snapfire_fsr_plan::Manifest;

use crate::BuildError;

pub const BODIES_FILE: &str = "generated/bodies.rs";

const ROOT: &str = "snapfire_fsr_host::bodies";

/// What the generator wrote for a plan.
#[derive(Debug, Clone, PartialEq)]
#[non_exhaustive]
pub struct Generated {
  pub text: String,
  /// Each lowered body the generator could not write, by row, with the reason; it runs interpreted.
  pub interpreted: Vec<(String, String)>,
}

/// Every lowered body of `manifest` by the row it answers: each source's body, `meta`, `store`, `defaults` and `paths`, each action and route handler, the middleware, the theme and each card image's `images`.
fn rows(manifest: &Manifest) -> Vec<(String, &snapfire_fsr_ir::Body)> {
  let mut rows = Vec::new();
  for row in manifest.lowered_sources() {
    for (export, body) in [("", &row.body), (" meta", &row.meta), (" store", &row.store), (" defaults", &row.defaults), (" paths", &row.paths)] {
      if let Some(body) = body {
        rows.push((format!("{}{export}", row.id), body));
      }
    }
  }
  rows.extend(manifest.lowered_actions().filter_map(|row| row.body.as_ref().map(|body| (row.id.clone(), body))));
  rows.extend(manifest.handlers.iter().filter_map(|row| row.body.as_ref().map(|body| (row.id.clone(), body))));
  rows.extend(manifest.middleware.as_ref().map(|body| ("middleware".to_owned(), body)));
  rows.extend(manifest.theme.as_ref().map(|body| ("theme".to_owned(), body)));
  rows.extend(manifest.images.iter().filter_map(|row| row.images.as_ref().map(|body| (format!("{} images", row.pattern), body))));
  rows
}

/// What [`file`] writes for `plan`, the plan text as written, with every body it could not write: every lowered body when `production`, none otherwise. Two rows with the same plan share one function.
pub fn generate(plan: &str, production: bool) -> Result<Generated, BuildError> {
  let mut out = String::from("// Generated by fsr from generated/plan.sexp.\n\n");
  let mut written: Vec<(String, u64, String)> = Vec::new();
  let mut interpreted = Vec::new();
  if production {
    let manifest = Manifest::from_text(plan).map_err(|e| BuildError::Dev(format!("{BODIES_FILE}: the plan does not read back: {e}")))?;
    let consts = (!manifest.consts.is_empty()).then_some(&manifest.consts);
    for (row, body) in rows(&manifest) {
      let plan = snapfire_fsr_ir::native::plan_hash(body, consts);
      if written.iter().any(|(_, written, _)| *written == plan) {
        continue;
      }
      let name = format!("body_{}", written.len());
      match snapfire_fsr_ir::native::emit_in(ROOT, &name, body, consts) {
        Ok(source) => {
          out.push_str(&source);
          out.push('\n');
          written.push((row, plan, name));
        }
        Err(why) => interpreted.push((row, why)),
      }
    }
  }
  let _ = writeln!(out, "pub static BODIES: &[{ROOT}::Native] = &[");
  for (row, plan, name) in &written {
    let _ = writeln!(out, "  {ROOT}::Native {{ source: {row:?}, plan: {plan}, body: {name} }},");
  }
  out.push_str("];\n");
  Ok(Generated { text: out, interpreted })
}

/// The file for `plan`: [`generate`]'s text.
pub fn file(plan: &str, production: bool) -> Result<String, BuildError> {
  generate(plan, production).map(|generated| generated.text)
}

/// Writes [`file`] under `app`, leaving it untouched when it already holds the same text so the crate including it does not rebuild. Each body it could not write is named on stderr with the reason.
pub fn write(app: &Path, plan: &str, production: bool) -> Result<Option<PathBuf>, BuildError> {
  let generated = generate(plan, production)?;
  for (row, why) in &generated.interpreted {
    eprintln!("bodies: {row} runs interpreted: {why}");
  }
  let path = app.join(BODIES_FILE);
  if std::fs::read_to_string(&path).is_ok_and(|current| current == generated.text) {
    return Ok(None);
  }
  std::fs::write(&path, generated.text).map_err(|e| BuildError::Io(path.clone(), e))?;
  Ok(Some(path))
}

#[cfg(test)]
mod tests {
  use super::*;

  const PLAN: &str = r#"{
    "version": 2,
    "routes": [],
    "sources": [
      { "id": "catalog", "owner": "lowered", "module": "app/routes/index/page.loader.ts",
        "body": [ { "return": { "object": [ { "field": [ "products", { "array": [] } ] } ] } } ] }
    ]
  }"#;

  #[test]
  fn a_production_build_writes_each_loader_with_the_plan_it_was_written_from() {
    let manifest = Manifest::from_text(PLAN).unwrap();
    let plan = snapfire_fsr_ir::native::plan_hash(manifest.sources[0].body.as_ref().unwrap(), None);
    let text = file(PLAN, true).unwrap();
    assert!(text.contains("pub fn body_0(f: &mut snapfire_fsr_host::bodies::Frame<'_>)"), "{text}");
    assert!(text.contains(&format!("Native {{ source: \"catalog\", plan: {plan}, body: body_0 }}")), "{text}");
  }

  const HANDLER_PLAN: &str = r#"{
    "version": 2,
    "routes": [],
    "handlers": [
      { "id": "api.products.GET", "method": "GET", "pattern": "/api/products", "owner": "lowered",
        "body": [ { "return": { "object": [ { "field": [ "products", { "array": [] } ] } ] } } ] }
    ]
  }"#;

  #[test]
  fn a_production_build_writes_each_route_handler_with_the_plan_it_was_written_from() {
    let manifest = Manifest::from_text(HANDLER_PLAN).unwrap();
    let plan = snapfire_fsr_ir::native::plan_hash(manifest.handlers[0].body.as_ref().unwrap(), None);
    let text = file(HANDLER_PLAN, true).unwrap();
    assert!(text.contains("pub fn body_0(f: &mut snapfire_fsr_host::bodies::Frame<'_>)"), "{text}");
    assert!(text.contains(&format!("Native {{ source: \"api.products.GET\", plan: {plan}, body: body_0 }}")), "{text}");
  }

  const EVERY_KIND: &str = r#"{
    "version": 2,
    "routes": [],
    "sources": [
      { "id": "catalog", "owner": "lowered", "module": "app/routes/index/page.loader.ts",
        "body": [ { "return": { "object": [ { "field": [ "products", { "array": [] } ] } ] } } ],
        "meta": [ { "return": { "object": [ { "field": [ "title", { "lit": { "str": "Catalog" } } ] } ] } } ],
        "store": [ { "return": { "object": [ { "field": [ "cart", { "array": [] } ] } ] } } ],
        "defaults": [ { "return": { "object": [ { "field": [ "theme", { "lit": { "str": "light" } } ] } ] } } ],
        "paths": [ { "return": { "array": [] } } ] }
    ],
    "actions": [
      { "id": "checkout", "owner": "lowered", "module": "app/routes/cart/actions.ts",
        "body": [ { "return": { "lit": { "str": "order-1" } } } ] }
    ],
    "handlers": [
      { "id": "api.products.GET", "method": "GET", "pattern": "/api/products", "owner": "lowered",
        "body": [ { "return": { "lit": { "str": "products" } } } ] },
      { "id": "api.ping.GET", "method": "GET", "pattern": "/api/ping", "owner": "lowered",
        "body": [ { "return": { "lit": { "str": "products" } } } ] },
      { "id": "api.ledger.GET", "method": "GET", "pattern": "/api/ledger", "owner": "lowered",
        "body": [ { "return": { "call": { "service": "ledger", "method": "list", "args": [] } } } ] }
    ],
    "middleware": [ { "return": { "lit": { "str": "next" } } } ],
    "theme": [ { "return": { "lit": { "str": "dark" } } } ]
  }"#;

  #[test]
  fn a_production_build_writes_every_kind_of_lowered_body() {
    let text = file(EVERY_KIND, true).unwrap();
    for row in ["catalog", "catalog meta", "catalog store", "catalog defaults", "catalog paths", "checkout", "api.products.GET", "middleware", "theme"] {
      assert!(text.contains(&format!("source: {row:?},")), "{row}: {text}");
    }
  }

  #[test]
  fn two_rows_with_the_same_plan_share_one_function() {
    let text = file(EVERY_KIND, true).unwrap();
    assert!(text.contains("source: \"api.products.GET\","), "{text}");
    assert!(!text.contains("source: \"api.ping.GET\","), "{text}");
  }

  #[test]
  fn a_body_the_generator_cannot_write_is_named_with_the_reason() {
    let generated = generate(EVERY_KIND, true).unwrap();
    assert_eq!(generated.interpreted.len(), 1, "{:?}", generated.interpreted);
    let (row, why) = &generated.interpreted[0];
    assert_eq!(row, "api.ledger.GET");
    assert!(!why.is_empty());
    assert!(!generated.text.contains("api.ledger.GET"), "{}", generated.text);
  }

  #[test]
  fn a_development_build_writes_no_loader() {
    let text = file(PLAN, false).unwrap();
    assert!(!text.contains("fn body_"), "{text}");
    assert!(text.contains("pub static BODIES: &[snapfire_fsr_host::bodies::Native] = &[\n];"), "{text}");
  }
}
