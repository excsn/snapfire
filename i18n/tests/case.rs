fn esc(s: &str) -> String {
  s.chars().map(|c| if c.is_ascii() { c.to_string() } else { format!("\\u{{{:x}}}", c as u32) }).collect()
}

#[test]
fn case_mapping_answers_what_node_answers() {
  let mut failed = Vec::new();
  for (text, locale, upper, lower) in NODE {
    let (got_upper, got_lower) = (upper_case(text, locale), lower_case(text, locale));
    if got_upper != *upper {
      failed.push(format!("upper {} {locale}: {}, want {}", esc(text), esc(&got_upper), esc(upper)));
    }
    if got_lower != *lower {
      failed.push(format!("lower {} {locale}: {}, want {}", esc(text), esc(&got_lower), esc(lower)));
    }
  }
  assert!(failed.is_empty(), "{} of {} mappings:\n{}", failed.len(), NODE.len() * 2, failed.join("\n"));
}
